import { PGlite } from '../../tmp/blood-bank-tests/node_modules/@electric-sql/pglite/dist/index.js';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

const db = new PGlite();
const hospital = randomUUID();
const session = randomUUID();
const room = randomUUID();
const incident = 7;
const patient = 11;

await db.exec(`
  create role anon;
  create role authenticated;
  create schema auth;
  create function auth.uid() returns uuid language sql stable
    as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;

  create table public.corvia_ws6_units_actual (
    unit_id bigint generated by default as identity primary key,
    registration_number text,
    compliance_expiry_date date
  );
  create table public.hospital_rooms (
    id uuid primary key,
    hospital_id uuid not null,
    capacity integer not null
  );
  create table public.hospital_beds (
    id uuid primary key default gen_random_uuid(),
    hospital_id uuid not null,
    room_id uuid not null,
    is_active boolean not null default true
  );
  create table public.corvia_ws6_patients_actual (
    patient_id bigint primary key,
    hospital_id uuid not null,
    patient_number text,
    identity_number text,
    first_name text,
    last_name text,
    date_of_birth date,
    sex text,
    patient_recorded_blood_type text
  );
  create table public.corvia_ws6_incident_patients (
    hospital_id uuid not null,
    incident_id bigint not null,
    patient_id bigint not null,
    is_active boolean not null default true
  );
  create table public.corvia_ws6_audit_logs (
    audit_log_id bigint generated by default as identity primary key,
    hospital_id uuid not null,
    user_id bigint,
    incident_id bigint,
    patient_id bigint,
    action_type text not null,
    entity_type text not null,
    entity_id bigint,
    old_value jsonb,
    new_value jsonb,
    reason text,
    action_datetime timestamptz not null default now(),
    device_id text
  );

  create function public.corvia_ems_check(uuid, uuid) returns void
    language plpgsql as $$ begin return; end $$;
  create function public.corvia_ems_allowed(uuid, bigint) returns boolean
    language sql stable as $$ select true $$;
  create function public.corvia_ems_member(uuid) returns bigint
    language sql stable as $$ select 1::bigint $$;

  insert into public.hospital_rooms values ('${room}', '${hospital}', 1);
  insert into public.corvia_ws6_patients_actual
    (patient_id, hospital_id, patient_number, first_name)
    values (${patient}, '${hospital}', 'EMS-P-11', 'Unknown');
  insert into public.corvia_ws6_incident_patients
    values ('${hospital}', ${incident}, ${patient}, true);
`);

const migration = await readFile(
  new URL('../../supabase/scripts/workstreams/18_install_live_qa_fixes.sql', import.meta.url),
  'utf8',
);
await db.exec(migration);
await db.exec(migration);

await assert.rejects(
  () => db.query('insert into corvia_ws6_units_actual(registration_number, compliance_expiry_date) values($1,$2)', ['', '2099-01-01']),
  /Registration number is required/,
);
await assert.rejects(
  () => db.query('insert into corvia_ws6_units_actual(registration_number, compliance_expiry_date) values($1,$2)', ['QA-1', '2000-01-01']),
  /cannot be in the past/,
);
await db.query(
  'insert into corvia_ws6_units_actual(registration_number, compliance_expiry_date) values($1,$2)',
  ['QA-1', '2099-01-01'],
);

await db.query(
  'insert into hospital_beds(hospital_id, room_id) values($1,$2)',
  [hospital, room],
);
await assert.rejects(
  () => db.query('insert into hospital_beds(hospital_id, room_id) values($1,$2)', [hospital, room]),
  /room is full/,
);

const user = randomUUID();
await db.query("select set_config('request.jwt.claim.sub',$1,false)", [user]);
await db.exec('set role authenticated');
const updated = (
  await db.query(
    'select public.corvia_ems_update_patient($1,$2,$3,$4,$5) value',
    [
      hospital,
      session,
      incident,
      patient,
      JSON.stringify({
        identity_number: 'QA-ID-11',
        first_name: 'Identified',
        last_name: 'Patient',
      }),
    ],
  )
).rows[0].value;

assert.equal(updated.first_name, 'Identified');
assert.equal(updated.identity_number, 'QA-ID-11');
await db.exec('reset role');
assert.equal(
  (await db.query("select count(*)::int count from corvia_ws6_audit_logs where action_type='patient_update'"))
    .rows[0].count,
  1,
);

console.log('PASS: live QA vehicle, bed capacity and patient update safeguards');
await db.close();
