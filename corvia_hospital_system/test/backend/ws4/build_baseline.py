"""Reconstruct the selected, deliberately vulnerable 2026-10-05 SQL contract.

Not a migration or a complete Supabase restore. See README.md for boundaries.
Only an explicitly supplied metadata file is read; no backend is queried.
"""
import argparse
import csv
import hashlib
import json
import re
from pathlib import Path

EXPECTED_HASH = '88d95114fb7c06a6b4fb2d525d299f6713fe4513be8053e3df63c6c189f852d5'
FUNCTIONS = (
    'block_user_type_change()', 'set_updated_at()', 'is_admin()',
    'corvia_lab_admin_disable_worker()', 'corvia_is_dispatch_operator()',
    'corvia_protect_incident_dispatch_assignment()',
    'corvia_dispatch_accept_incident(bigint)',
)
TABLES = ('profiles', 'incidents')
EXCLUDED_PROFILE_READ_POLICIES = {
    'Doctors can view linked patient profiles',
    'Hospital admins can view patient profiles in their hospital',
    'Pharmacists read dispensing patient profiles',
}


def ident(value):
    return '"' + value.replace('"', '""') + '"'


def generate(source):
    if hashlib.sha256(source.read_bytes()).hexdigest() != EXPECTED_HASH:
        raise ValueError('Catalog changed. Review the new export before rebuilding this baseline.')
    csv.field_size_limit(20_000_000)
    with source.open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream))
    if len(rows) != 2410 or any(int(r['total_rows']) != 2410 for r in rows):
        raise ValueError('Incomplete catalog export')
    for i, row in enumerate(rows, 1):
        row['record'] = i
        row['parsed'] = json.loads(row['details'])
    used = []

    def record(row):
        used.append({'record': row['record'], 'section': row['section'], 'object': row['object_name']})

    def one(section, name):
        found = [r for r in rows if r['section'] == section and r['object_name'] == name]
        if len(found) != 1:
            raise ValueError(f'Expected one catalog entry: {section}/{name}')
        record(found[0])
        return found[0]['parsed']

    sql = ["""-- TEST BASELINE ONLY: contains known permission defects, never deploy.
-- Extracted selected catalog contract, not a complete Supabase database.
CREATE ROLE supabase_admin NOLOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE SCHEMA auth;
-- Synthetic identity boundary: models only auth UID, not Auth/JWT verification.
CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role, supabase_admin;
GRANT EXECUTE ON FUNCTION auth.uid() TO PUBLIC;
-- Resolve deparsed catalog uid()/REFERENCES users to auth.
SET search_path = public, auth;
-- Dependency stub only: preserves the actual profile trigger's dispatch branch.
-- Does not model or certify the lab product's tables/permissions.
CREATE TABLE public.lab_worker_accounts (
  profile_id uuid, is_active boolean, can_verify_results boolean, updated_at timestamptz
);
ALTER TABLE public.lab_worker_accounts OWNER TO supabase_admin;
"""]
    for table in TABLES:
        columns = sorted((r for r in rows if r['section'] == '05_ws4_column'
                          and r['object_name'].startswith(f'public.{table}.')),
                         key=lambda r: r['parsed']['position'])
        definitions = []
        for row in columns:
            record(row)
            data = row['parsed']
            definition = ident(row['object_name'].split('.')[-1]) + ' ' + data['type']
            if data['identity']:
                definition += ' GENERATED ALWAYS AS IDENTITY' if data['identity'] == 'a' else ' GENERATED BY DEFAULT AS IDENTITY'
            elif data['default'] is not None:
                definition += ' DEFAULT ' + data['default']
            if data['not_null']:
                definition += ' NOT NULL'
            definitions.append(definition)
        sql.append(f'CREATE TABLE public.{table} (\n  ' + ',\n  '.join(definitions) + '\n);')
        constraints = [r for r in rows if r['section'] == '07_constraint' and r['object_name'].startswith(f'public.{table}.')]
        constraint_names = set()
        for row in constraints:
            record(row)
            name = row['object_name'].split('.')[-1]
            constraint_names.add(name)
            sql.append(f'ALTER TABLE public.{table} ADD CONSTRAINT {ident(name)} {row["parsed"]["definition"]};')
        for row in rows:
            if row['section'] == '08_index' and row['parsed']['table'] == table:
                record(row)
                if row['object_name'].split('.')[-1] not in constraint_names:
                    sql.append(row['parsed']['definition'] + ';')
        sql.append(f'ALTER TABLE public.{table} OWNER TO supabase_admin;')
        relation = one('04_relation_security', 'public.' + table)
        if relation['rls_enabled']:
            sql.append(f'ALTER TABLE public.{table} ENABLE ROW LEVEL SECURITY;')
        if relation['rls_forced']:
            sql.append(f'ALTER TABLE public.{table} FORCE ROW LEVEL SECURITY;')
        for role in ('anon', 'authenticated', 'service_role'):
            if f'{role}=arwdDxt/' not in relation['acl']:
                raise ValueError('Review changed table privileges: ' + table)
            sql.append(f'GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON public.{table} TO {role};')
    for signature in FUNCTIONS:
        catalog_signature = signature.replace('(bigint)', '(p_incident_id bigint)')
        data = one('01_function', 'public.' + catalog_signature)
        sql.append(data['definition'].replace('\r', '').rstrip().rstrip(';') + ';')
        sql.append(f'ALTER FUNCTION public.{signature} OWNER TO supabase_admin;')
        sql.append(f'REVOKE ALL ON FUNCTION public.{signature} FROM PUBLIC;')
        for role in ('PUBLIC', 'anon', 'authenticated', 'service_role'):
            token = '=X/' if role == 'PUBLIC' else role+'=X/'
            if (role == 'PUBLIC' and re.search(r'(?:\{|,)=X/', data['acl'])) or (role != 'PUBLIC' and token in data['acl']):
                sql.append(f'GRANT EXECUTE ON FUNCTION public.{signature} TO {role};')
    for row in rows:
        if row['section'] == '02_trigger' and any(row['object_name'].startswith(f'public.{t}.') for t in TABLES):
            record(row)
            if row['parsed']['enabled_mode'] != 'O':
                raise ValueError('Review nondefault trigger mode')
            sql.append(row['parsed']['definition'] + ';')
        if row['section'] == '03_policy' and row['parsed']['tablename'] in TABLES:
            if row['parsed']['tablename'] == 'profiles' and row['parsed']['policyname'] in EXCLUDED_PROFILE_READ_POLICIES:
                # Additional permissive SELECT routes for unrelated products;
                # own-profile SELECT remains exact. No write policy is omitted.
                if row['parsed']['cmd'] != 'SELECT' or row['parsed']['permissive'] != 'PERMISSIVE':
                    raise ValueError('Excluded read policy changed meaning')
                continue
            record(row)
            data = row['parsed']
            policy = f'CREATE POLICY {ident(data["policyname"])} ON public.{data["tablename"]} AS {data["permissive"]} FOR {data["cmd"]} TO '
            policy += ', '.join(ident(r) if r != 'public' else 'PUBLIC' for r in data['roles'])
            if data['qual'] is not None:
                policy += ' USING (' + data['qual'] + ')'
            if data['with_check'] is not None:
                policy += ' WITH CHECK (' + data['with_check'] + ')'
            sql.append(policy + ';')
    return '\n\n'.join(sql) + '\n', {'source_sha256': EXPECTED_HASH, 'records': used,
        'omitted_permissive_profile_select_policies': sorted(EXCLUDED_PROFILE_READ_POLICIES),
        'boundaries': ['auth.users and auth.uid are synthetic identity substitutes',
                       'lab_worker_accounts is a trigger dependency stub; no lab verification',
                       'only profiles/incidents contract objects reconstructed; not Auth/API/Realtime',
                       'no deployment or full database backup; includes known unsafe permissions']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Compare without rewriting generated files')
    args = parser.parse_args()
    sql, provenance = generate(args.catalog)
    root = Path(__file__).parent / 'baseline'
    outputs = {'catalog.sql': sql, 'provenance.json': json.dumps(provenance, indent=2)+'\n'}
    if args.check:
        for name, content in outputs.items():
            if (root/name).read_text(encoding='utf-8') != content:
                raise ValueError('Generated baseline differs: ' + name)
        print('Catalog baseline matches the pinned source and generator.')
    else:
        root.mkdir(exist_ok=True)
        for name, content in outputs.items():
            (root/name).write_text(content, encoding='utf-8', newline='\n')
        print('Generated selected catalog baseline and provenance.')


if __name__ == '__main__':
    main()
