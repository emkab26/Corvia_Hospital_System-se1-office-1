$$;

create or replace function public.corvia_ws6_actual_register_shift(
  p_hospital_id uuid,
  p_unit_id bigint,
  p_display_name text,
  p_employee_number text,
  p_role text default 'Paramedic',
  p_verification_status text default 'Pending',
  p_auth_user_id uuid default null,
  p_start_datetime timestamptz default now(),
  p_end_datetime timestamptz default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_first text;
  v_last text;
  v_member public.corvia_ws6_ems_members;
  v_shift public.corvia_ws6_shifts_actual;
  v_crew public.corvia_ws6_crews;
  v_link public.corvia_ws6_crew_members_actual;
  v_end timestamptz := coalesce(p_end_datetime, p_start_datetime + interval '12 hours');
  v_status text := lower(coalesce(p_verification_status, 'pending'));
begin
  if not public.corvia_ws6_is_hospital_admin(p_hospital_id) then
    raise exception 'Hospital administrator access is required';
  end if;
  if nullif(trim(coalesce(p_display_name, '')), '') is null then
    raise exception 'Crew member name is required';
  end if;
  if nullif(trim(coalesce(p_employee_number, '')), '') is null then
    raise exception 'Employee number is required';
  end if;
  if v_status not in ('verified', 'pending', 'suspended', 'expired') then
    raise exception 'Invalid verification status';
  end if;
  if v_end <= p_start_datetime then
    raise exception 'Shift end must be after shift start';
  end if;
  if not exists (select 1 from public.corvia_ws6_units_actual
    where unit_id = p_unit_id and hospital_id = p_hospital_id and is_active) then
    raise exception 'Active unit not found';
  end if;

  v_first := split_part(trim(p_display_name), ' ', 1);
  v_last := nullif(trim(substr(trim(p_display_name), length(v_first) + 1)), '');
  insert into public.corvia_ws6_ems_members(
    hospital_id, employee_number, first_name, last_name, verification_status,
    is_active, auth_user_id
  ) values (
    p_hospital_id, trim(p_employee_number), v_first, v_last, v_status, true, p_auth_user_id
  ) on conflict (hospital_id, employee_number) do update set
    first_name = excluded.first_name, last_name = excluded.last_name,
    verification_status = excluded.verification_status, is_active = true,
    auth_user_id = coalesce(excluded.auth_user_id, public.corvia_ws6_ems_members.auth_user_id)
  returning * into v_member;

  insert into public.corvia_ws6_shifts_actual(
    hospital_id, member_id, unit_id, start_datetime, end_datetime,
    shift_status, verified_at
  ) values (
    p_hospital_id, v_member.member_id, p_unit_id, p_start_datetime, v_end,
    case when v_status = 'verified' and p_start_datetime <= now() and v_end > now()
      then 'Active' else 'Scheduled' end,
    case when v_status = 'verified' then now() end
  ) returning * into v_shift;
  insert into public.corvia_ws6_crews(
    hospital_id, crew_code, unit_id, shift_id, crew_status, start_datetime, end_datetime
  ) values (
    p_hospital_id, 'CREW-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
    p_unit_id, v_shift.shift_id,
    case when v_status = 'verified' then 'Active' else 'Unavailable' end,
    p_start_datetime, v_end
  ) returning * into v_crew;
  insert into public.corvia_ws6_crew_members_actual(
    hospital_id, crew_id, member_id, crew_role
  ) values (p_hospital_id, v_crew.crew_id, v_member.member_id,
    coalesce(nullif(trim(p_role), ''), 'Paramedic')) returning * into v_link;

  insert into public.corvia_ws6_audit_logs(
    hospital_id, user_id, action_type, entity_type, entity_id, new_value
  ) values (p_hospital_id, v_member.member_id, 'ShiftRegistered', 'Shift', v_shift.shift_id,
    jsonb_build_object('unit_id', p_unit_id, 'crew_id', v_crew.crew_id,
      'employee_number', v_member.employee_number));
  return jsonb_build_object('member_id', v_member.member_id::text,
    'shift_id', v_shift.shift_id::text, 'crew_id', v_crew.crew_id::text,
    'crew_member_id', v_link.crew_member_id::text);
end;
$$;

create or replace function public.corvia_ws6_actual_assign_unit(
  p_hospital_id uuid,
  p_incident_id bigint,
  p_unit_id bigint,
  p_expected_revision bigint default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_unit public.corvia_ws6_units_actual;
  v_incident public.corvia_ws6_incidents_actual;
  v_crew public.corvia_ws6_crews;
  v_assignment public.corvia_ws6_incident_assignments_actual;
begin
  if not public.corvia_ws6_is_hospital_admin(p_hospital_id) then
    raise exception 'Hospital administrator access is required';
  end if;
  select * into v_unit from public.corvia_ws6_units_actual
  where unit_id = p_unit_id and hospital_id = p_hospital_id and is_active for update;
  if not found then raise exception 'Unit not found'; end if;
  if p_expected_revision is not null and v_unit.availability_revision <> p_expected_revision then
    raise exception 'Unit availability changed; refresh before assigning';
  end if;
  if v_unit.readiness_status not in ('idle', 'ready') then
    raise exception 'Unit is not available for assignment';
  end if;
  select c.* into v_crew
  from public.corvia_ws6_crews c
  join public.corvia_ws6_shifts_actual s on s.shift_id = c.shift_id
  join public.corvia_ws6_ems_members m on m.member_id = s.member_id
  where c.hospital_id = p_hospital_id and c.unit_id = p_unit_id
    and c.crew_status = 'Active' and s.shift_status = 'Active'
    and m.verification_status = 'verified' and m.is_active
    and s.start_datetime <= now() and (s.end_datetime is null or s.end_datetime > now())
  order by c.start_datetime desc limit 1;
  if not found then raise exception 'Unit has no active verified crew shift'; end if;
  select * into v_incident from public.corvia_ws6_incidents_actual
  where incident_id = p_incident_id and hospital_id = p_hospital_id for update;
  if not found then raise exception 'Incident not found'; end if;
  if v_incident.status not in ('Dispatched', 'Accepted') then
    raise exception 'Incident is not assignable';
  end if;
  if exists (select 1 from public.corvia_ws6_incident_assignments_actual
    where incident_id = p_incident_id and is_active) then
    raise exception 'Incident already has an active crew';
  end if;

  insert into public.corvia_ws6_incident_assignments_actual(
    hospital_id, incident_id, crew_id, assigned_datetime, assignment_status, is_active
  ) values (p_hospital_id, p_incident_id, v_crew.crew_id, now(), 'Assigned', true)
  returning * into v_assignment;
  update public.corvia_ws6_units_actual set
    status = 'Assigned', readiness_status = 'en_route',
    availability_revision = availability_revision + 1
  where unit_id = p_unit_id;
  update public.corvia_ws6_incidents_actual set
    status = 'Accepted', assigned_datetime = coalesce(assigned_datetime, now())
  where incident_id = p_incident_id;
  insert into public.corvia_ws6_incident_status_history(
    hospital_id, incident_id, status, status_datetime, sync_status
  ) values (p_hospital_id, p_incident_id, 'Accepted', now(), 'Sent');
  insert into public.corvia_ws6_audit_logs(
    hospital_id, action_type, entity_type, entity_id, new_value
  ) values (p_hospital_id, 'UnitAssigned', 'IncidentAssignment', v_assignment.assignment_id,
    jsonb_build_object('incident_id', p_incident_id, 'unit_id', p_unit_id, 'crew_id', v_crew.crew_id));
  return jsonb_build_object('id', v_assignment.assignment_id::text,
    'incident_id', p_incident_id::text, 'unit_id', p_unit_id::text,
    'crew_id', v_crew.crew_id::text, 'status', 'assigned');
end;
$$;

create or replace function public.corvia_ws6_actual_set_unit_status(
  p_hospital_id uuid,
  p_unit_id bigint,
  p_new_status text,
  p_expected_revision bigint default null,
  p_reason text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_unit public.corvia_ws6_units_actual;
  v_status text := lower(coalesce(p_new_status, 'idle'));
  v_db_status text;
begin
  if not public.corvia_ws6_is_hospital_admin(p_hospital_id) then
    raise exception 'Hospital administrator access is required';
  end if;
  if v_status not in ('ready', 'idle', 'en_route', 'on_scene', 'transporting', 'maintenance', 'off_duty') then
    raise exception 'Invalid unit status';
  end if;
  select * into v_unit from public.corvia_ws6_units_actual
  where unit_id = p_unit_id and hospital_id = p_hospital_id and is_active for update;
  if not found then raise exception 'Unit not found'; end if;
  if p_expected_revision is not null and v_unit.availability_revision <> p_expected_revision then
    raise exception 'Unit availability changed; refresh before updating';
  end if;
  if v_status in ('ready', 'idle') and exists (
    select 1 from public.corvia_ws6_incident_assignments_actual a
    join public.corvia_ws6_crews c on c.crew_id = a.crew_id
    where c.unit_id = p_unit_id and a.is_active
  ) then
    raise exception 'An active assignment keeps this unit unavailable';
  end if;
  v_db_status := case when v_status in ('maintenance', 'off_duty') then 'Out of Service'
    when v_status = 'idle' or v_status = 'ready' then 'Available' else 'Assigned' end;
  update public.corvia_ws6_units_actual set
    status = v_db_status, readiness_status = v_status,
    availability_revision = availability_revision + 1
  where unit_id = p_unit_id returning * into v_unit;
  insert into public.corvia_ws6_audit_logs(
    hospital_id, action_type, entity_type, entity_id, reason, new_value
  ) values (p_hospital_id, 'UnitStatusChanged', 'Unit', p_unit_id, p_reason,
    jsonb_build_object('status', v_status, 'database_status', v_db_status));
  return jsonb_build_object('id', v_unit.unit_id::text, 'call_sign', v_unit.unit_number,
    'unit_type', lower(v_unit.vehicle_type), 'readiness_status', v_unit.readiness_status,
    'availability_revision', v_unit.availability_revision, 'status', v_unit.status);
end;
$$;

