create or replace function public.corvia_ws6_actual_create_incident(
  p_hospital_id uuid,
  p_priority text,
  p_summary text,
  p_incident_type text default 'Medical Emergency',
  p_scene_address text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
