    'corvia_ws6_clinical_notes', 'corvia_ws6_treatments',
    'corvia_ws6_treatment_timeline', 'corvia_ws6_receiving_facilities',
    'corvia_ws6_handovers', 'corvia_ws6_offline_sync_queue',
    'corvia_ws6_device_sessions', 'corvia_ws6_audit_logs',
    'corvia_ws6_notification_settings'
  ] loop
    execute format('alter table public.%I enable row level security', v_table);
    execute format('revoke all on table public.%I from anon, authenticated', v_table);
  end loop;
end;
$$;

create or replace function public.corvia_ws6_actual_dashboard(p_hospital_id uuid)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_result jsonb;
begin
  if not public.corvia_ws6_is_hospital_admin(p_hospital_id) then
    raise exception 'Hospital administrator access is required';
  end if;

  select jsonb_build_object(
    'units', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', u.unit_id::text,
        'call_sign', u.unit_number,
        'unit_type', lower(u.vehicle_type),
        'readiness_status', u.readiness_status,
        'availability_revision', u.availability_revision,
        'status', u.status,
        'registration_number', u.registration_number,
        'base_location', u.base_location
      ) order by u.unit_number)
      from public.corvia_ws6_units_actual u
      where u.hospital_id = p_hospital_id and u.is_active
    ), '[]'::jsonb),
    'incidents', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', i.incident_id::text,
        'incident_number', i.incident_number,
        'priority', lower(i.priority),
        'status', lower(replace(i.status, ' ', '_')),
        'summary', coalesce(i.dispatch_notes, i.incident_type),
        'incident_type', i.incident_type,
        'scene_address', i.scene_address,
        'created_at', i.created_datetime
      ) order by i.created_datetime desc)
      from public.corvia_ws6_incidents_actual i
      where i.hospital_id = p_hospital_id and i.status <> 'Closed'
    ), '[]'::jsonb),
    'assignments', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', a.assignment_id::text,
        'incident_id', a.incident_id::text,
        'unit_id', c.unit_id::text,
        'crew_id', a.crew_id::text,
        'status', lower(a.assignment_status)
      ) order by a.assigned_datetime desc)
      from public.corvia_ws6_incident_assignments_actual a
      join public.corvia_ws6_crews c on c.crew_id = a.crew_id
      where a.hospital_id = p_hospital_id and a.is_active
    ), '[]'::jsonb),
    'active_shifts', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', s.shift_id::text,
        'unit_id', s.unit_id::text,
        'crew_member_id', cm.crew_member_id::text,
        'display_name', trim(concat(m.first_name, ' ', coalesce(m.last_name, ''))),
        'staff_identifier', m.employee_number,
        'status', lower(s.shift_status),
        'starts_at', s.start_datetime,
        'ends_at', s.end_datetime
      ) order by s.start_datetime desc)
      from public.corvia_ws6_shifts_actual s
      join public.corvia_ws6_crew_members_actual cm on cm.member_id = s.member_id and cm.is_active
      join public.corvia_ws6_ems_members m on m.member_id = s.member_id
      where s.hospital_id = p_hospital_id
        and s.shift_status = 'Active'
        and s.start_datetime <= now()
        and (s.end_datetime is null or s.end_datetime > now())
    ), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;

