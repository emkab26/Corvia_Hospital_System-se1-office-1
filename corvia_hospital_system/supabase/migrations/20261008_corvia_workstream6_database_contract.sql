  insert into public.corvia_ws6_audit_logs(
    hospital_id, action_type, entity_type, entity_id, new_value
  ) values (p_hospital_id, 'IncidentCreated', 'Incident', v_incident.incident_id,
    jsonb_build_object('incident_number', v_incident.incident_number, 'priority', v_incident.priority));
  return jsonb_build_object('id', v_incident.incident_id::text,
    'incident_number', v_incident.incident_number, 'priority', lower(v_incident.priority),
    'status', lower(replace(v_incident.status, ' ', '_')), 'summary', v_incident.dispatch_notes);
